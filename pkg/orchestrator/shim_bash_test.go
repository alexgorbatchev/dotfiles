package orchestrator

import (
	"context"
	"path/filepath"
	"strings"
	"testing"

	"github.com/alexgorbatchev/dotfiles/pkg/config"
	"github.com/alexgorbatchev/dotfiles/pkg/fs"
)

// A shim names the bash that runs it by absolute path, so it still starts under a PATH
// without bash on it. When bash is itself a tool this project manages, its shim comes
// first on PATH, and a shim run by a shim would never reach bash.
func TestGenerateToolWritesTheResolvedBashIntoTheShebang(t *testing.T) {
	const targetDir = "/home/user/dotfiles/.generated/bin"
	projCfg := &config.ProjectConfig{
		Paths: config.PathsConfig{
			HomeDir:      "/home/user",
			DotfilesDir:  "/home/user/dotfiles",
			GeneratedDir: "/home/user/dotfiles/.generated",
			TargetDir:    targetDir,
			BinariesDir:  "/home/user/dotfiles/.generated/binaries",
		},
	}
	tool := &config.ToolConfig{
		Name:               "typescript",
		InstallationMethod: "github-release",
		Binaries:           []interface{}{map[string]interface{}{"name": "tsserver"}},
	}
	t.Setenv("PATH", targetDir+":/usr/local/bin")

	t.Run("bash on PATH behind its own shim", func(t *testing.T) {
		memFS := fs.NewMemFS()
		for path, content := range map[string]string{
			targetDir + "/bash":   "#!/usr/local/bin/bash\n# Shim for bash\n# Generated by Dotfiles Management Tool\n",
			"/usr/local/bin/bash": "bash",
		} {
			if err := memFS.MkdirAll(filepath.Dir(path), 0755); err != nil {
				t.Fatalf("creating %s: %v", filepath.Dir(path), err)
			}
			if err := memFS.WriteFile(path, []byte(content), 0755); err != nil {
				t.Fatalf("writing %s: %v", path, err)
			}
		}
		orch := newTestOrchestrator(t, memFS, "/home/user/dotfiles/dotfiles.config.ts")

		if err := orch.GenerateTool(context.Background(), tool, projCfg); err != nil {
			t.Fatalf("GenerateTool: %v", err)
		}
		shim, err := memFS.ReadFile(targetDir + "/tsserver")
		if err != nil {
			t.Fatalf("reading the shim: %v", err)
		}
		if firstLine, _, _ := strings.Cut(string(shim), "\n"); firstLine != "#!/usr/local/bin/bash" {
			t.Errorf("shebang = %q, want #!/usr/local/bin/bash", firstLine)
		}
	})

	t.Run("no bash", func(t *testing.T) {
		orch := newTestOrchestrator(t, fs.NewMemFS(), "/home/user/dotfiles/dotfiles.config.ts")

		err := orch.GenerateTool(context.Background(), tool, projCfg)
		if err == nil || !strings.Contains(err.Error(), `resolving the bash that runs shims: system binary "bash" not found`) {
			t.Fatalf("GenerateTool error = %v, want the missing bash reported", err)
		}
	})
}
